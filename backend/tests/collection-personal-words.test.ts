it('keeps legacy words and photos when attaching or deleting a collection; attachments are atomic and idempotent',async()=>{
  const id=await create('Từ cũ'),next=await create('Bộ sau');
  const legacy=await PersonalWord.create({userId:owner,...word});
  const foreign=await PersonalWord.create({userId:other,...word});
  const path=base+'/'+id+'/personal-words';
  const available=(await request(app).get(path+'/available').set('Authorization',auth).expect(200)).body.data.items;
  expect(available.find((row:any)=>row._id===String(legacy._id))).toMatchObject({word:word.word});expect(JSON.stringify(available)).not.toContain(photo);
  await request(app).post(path+'/attach').set('Authorization',auth).send({wordIds:[String(legacy._id),String(foreign._id)]}).expect(404);
  expect((await PersonalWord.findById(legacy._id))!.collectionId).toBeUndefined();
  for(let i=0;i<2;i++)await request(app).post(path+'/attach').set('Authorization',auth).send({wordIds:[String(legacy._id)]}).expect(200);
  await request(app).post(base+'/'+next+'/personal-words/attach').set('Authorization',auth).send({wordIds:[String(legacy._id)]}).expect(404);
  await request(app).delete(base+'/'+id).set('Authorization',auth).expect(200);
  const kept=await PersonalWord.findById(legacy._id);expect(kept).toMatchObject(word);expect(kept!.collectionId).toBeUndefined();
  await request(app).post(base+'/'+next+'/personal-words/attach').set('Authorization',auth).send({wordIds:[String(legacy._id)]}).expect(200);
  expect((await request(app).get(base+'/'+next+'/personal-words/'+legacy._id).set('Authorization',auth).expect(200)).body.data.imageUrl).toBe(photo);
});
