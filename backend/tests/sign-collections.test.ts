import {beforeAll,afterAll,describe,it,expect,vi} from 'vitest';
import request from 'supertest';
import {Types} from 'mongoose';
import {connectDatabase,disconnectDatabase} from '../src/config/database';
import {createApp} from '../src/app';
import {Category,DictionaryEntry,User,AuthSession,UserSettings} from '../src/models';
import {SignCollection,SignNote} from '../src/models/SignCollection.model';
import {ReviewQuiz} from '../src/models/ReviewQuiz.model';
import {WordProgress,TopicEnrollment} from '../src/models/Learning.model';
import {LearningEvent} from '../src/models/LearningEvent.model';
import {ensureLearningIndexes} from '../src/services/learning-indexes.service';
import {clearOwnedData,userTransaction} from '../src/services/user-data.service';

let app:Awaited<ReturnType<typeof createApp>>,owner:Types.ObjectId,other:Types.ObjectId;
let auth:string,otherAuth:string,id:string,code:string;
const topics:Types.ObjectId[]=[],entries:Types.ObjectId[]=[];
const base='/api/v1/sign-collections';
beforeAll(async()=>{
  await connectDatabase();app=await createApp();await ReviewQuiz.init();
  await ReviewQuiz.collection.createIndex({userId:1,topicId:1},{name:'userId_1_topicId_1',unique:true,partialFilterExpression:{status:'DRAFT'}});
  await ensureLearningIndexes();await Promise.all([WordProgress.init(),TopicEnrollment.init()]);
  const a=await request(app).post('/api/v1/auth/guest').send({}).expect(201),b=await request(app).post('/api/v1/auth/guest').send({}).expect(201);
  owner=new Types.ObjectId(a.body.data.user.id);other=new Types.ObjectId(b.body.data.user.id);
  auth=`Bearer ${a.body.data.tokens.accessToken}`;otherAuth=`Bearer ${b.body.data.tokens.accessToken}`;
  for(let i=0;i<3;i++)topics.push((await Category.create({name:'Collection QA '+i,slug:'collection-qa-'+Date.now()+'-'+i,status:i===2?'ARCHIVED':'ACTIVE'}))._id);
  for(let i=0;i<14;i++)entries.push((await DictionaryEntry.create({word:'Ký hiệu '+String(i).padStart(2,'0'),definition:'Nghĩa đã duyệt '+i,
    categoryId:topics[i===13?2:i%2],createdBy:owner,status:i===12?'DRAFT':'PUBLISHED',videoUrl:'https://example.com/'+i+'.mp4'}))._id);
});
afterAll(async()=>{
  await DictionaryEntry.deleteMany({_id:{$in:entries}});await Category.deleteMany({_id:{$in:topics}});
  for(const userId of [owner,other])for(const model of [SignCollection,SignNote,ReviewQuiz,WordProgress,TopicEnrollment,LearningEvent,AuthSession,UserSettings,User])await model.collection.deleteMany(model===User?{_id:userId}:{userId});
  await disconnectDatabase();
});
describe('Sign collections',()=>{
  it('migrates only the legacy draft index and creates bounded owner indexes',async()=>{
    const indexes=await ReviewQuiz.collection.indexes();
    expect(indexes.some(row=>row.name==='userId_1_topicId_1')).toBe(false);
    expect(indexes.some(row=>row.name==='draft_topic_scope' && row.unique)).toBe(true);
    expect(indexes.some(row=>row.name==='draft_collection_scope' && row.unique)).toBe(true);
    await ensureLearningIndexes();
    const explain=await SignCollection.find({userId:owner}).sort({updatedAt:-1,_id:1}).explain('executionStats');
    expect(JSON.stringify(explain)).toContain('IXSCAN');
  });
  it('requires authentication, validates inputs and never accepts a supplied owner',async()=>{
    await request(app).get(base).expect(401);
    await request(app).post(base).set('Authorization',auth).send({name:' '}).expect(400);
    await request(app).post(base).set('Authorization',auth).send({name:'Riêng',userId:String(other)}).expect(400);
    const created=await request(app).post(base).set('Authorization',auth).send({name:'Đi khám bệnh',description:'Bộ kết hợp nhiều chủ đề.'}).expect(201);
    id=created.body.data._id;expect(created.body.data.wordCount).toBe(0);
    await request(app).get(base+'/'+id).set('Authorization',otherAuth).expect(404);
    await request(app).patch(base+'/'+id).set('Authorization',otherAuth).send({name:'Chiếm quyền'}).expect(404);
    await request(app).delete(base+'/'+id).set('Authorization',otherAuth).expect(404);
    await request(app).post(base+'/'+id+'/share').set('Authorization',otherAuth).send({enabled:true}).expect(404);
  });
  it('adds dictionary references idempotently and excludes unpublished/inactive entries',async()=>{
    await request(app).post(base+'/'+id+'/entries').set('Authorization',auth).send({entryIds:[String(entries[12])]}).expect(409);
    await request(app).post(base+'/'+id+'/entries').set('Authorization',auth).send({entryIds:[String(entries[13])]}).expect(409);
    const ids=entries.slice(0,12).map(String);
    const saved=await request(app).post(base+'/'+id+'/entries').set('Authorization',auth).send({entryIds:ids}).expect(200);
    expect(saved.body.data.added).toBe(12);
    const repeated=await request(app).post(base+'/'+id+'/entries').set('Authorization',auth).send({entryIds:ids.slice(0,2)}).expect(200);
    expect(repeated.body.data.added).toBe(0);
    const raw=await SignCollection.findById(id).lean();expect(raw!.entryIds).toHaveLength(12);expect(raw).not.toHaveProperty('videoUrl');
    const page=await request(app).get(base+'/'+id+'/candidates?page=2').set('Authorization',auth).expect(200);
    expect(page.body.data.pagination.total).toBe(12);expect(page.body.data.items).toHaveLength(2);expect(page.body.data.items.every((row:any)=>row.inCollection)).toBe(true);
  });
  it('returns paged words and shared canonical progress without N+1 collection queries',async()=>{
    await WordProgress.create({userId:owner,entryId:entries[0],topicId:topics[0],stage:'REVIEW'});
    const spy=vi.spyOn(SignCollection,'aggregate');
    const list=await request(app).get(base).set('Authorization',auth).expect(200);
    expect(spy).toHaveBeenCalledOnce();spy.mockRestore();
    expect(list.body.data.items[0]).toMatchObject({wordCount:12,reviewCount:1});
    const page=await request(app).get(base+'/'+id).set('Authorization',auth).expect(200);
    expect(page.body.data.items).toHaveLength(10);expect(page.body.data.summary).toMatchObject({total:12,review:1,learning:11});
    const search=await request(app).get(base+'/'+id+'?search=11').set('Authorization',auth).expect(200);expect(search.body.data.items).toHaveLength(1);
  });
  it('stores a note per owner and entry, not per collection',async()=>{
    await request(app).put('/api/v1/sign-notes/'+entries[0]).set('Authorization',auth).send({text:'Ghi chú riêng không được chia sẻ.'}).expect(200);
    const otherNote=await request(app).get('/api/v1/sign-notes/'+entries[0]).set('Authorization',otherAuth).expect(200);expect(otherNote.body.data.text).toBe('');
    const detail=await request(app).get(base+'/'+id).set('Authorization',auth).expect(200);expect(detail.body.data.items[0].personalNote).toContain('Ghi chú riêng');
    await request(app).put('/api/v1/sign-notes/'+entries[0]).set('Authorization',auth).send({text:'a'.repeat(2001)}).expect(400);
    expect(await SignNote.countDocuments({userId:owner,entryId:entries[0]})).toBe(1);
  });
  it('shares only public dictionary content and imports an independent copy, once',async()=>{
    const shared=await request(app).post(base+'/'+id+'/share').set('Authorization',auth).send({enabled:true}).expect(200);code=shared.body.data.shareCode;
    expect(code).toMatch(/^[a-f0-9]{32}$/);
    const repeated=await request(app).post(base+'/'+id+'/share').set('Authorization',auth).send({enabled:true}).expect(200);expect(repeated.body.data.shareCode).toBe(code);
    const preview=await request(app).get('/api/v1/shared-collections/'+code).expect(200);
    for(const value of [String(owner),'Ghi chú riêng','shareToken','personalNote','progress'])expect(JSON.stringify(preview.body)).not.toContain(value);
    expect(preview.body.data).not.toHaveProperty('summary');expect(preview.headers['cache-control']).toBe('no-store');
    const imported=await request(app).post(base+'/import').set('Authorization',otherAuth).send({code}).expect(200);
    const again=await request(app).post(base+'/import').set('Authorization',otherAuth).send({code}).expect(200);
    expect(again.body.data).toMatchObject({_id:imported.body.data._id,alreadySaved:true});
    await request(app).patch(base+'/'+imported.body.data._id).set('Authorization',otherAuth).send({name:'Bản riêng'}).expect(200);
    expect((await SignCollection.findById(id))!.name).toBe('Đi khám bệnh');
    expect(await SignNote.countDocuments({userId:other})).toBe(0);
  });
  it('revokes sharing and live references follow media changes in owner and imported collections',async()=>{
    await DictionaryEntry.updateOne({_id:entries[0]},{$set:{videoUrl:'https://example.com/updated.mp4'}});
    const mine=await request(app).get(base+'/'+id).set('Authorization',auth).expect(200);expect(mine.body.data.items[0].videoUrl).toContain('updated');
    const copy=await SignCollection.findOne({userId:other});
    const theirs=await request(app).get(base+'/'+copy!._id).set('Authorization',otherAuth).expect(200);expect(theirs.body.data.items[0].videoUrl).toContain('updated');
    await request(app).post(base+'/'+id+'/share').set('Authorization',auth).send({enabled:false}).expect(200);
    await request(app).get('/api/v1/shared-collections/'+code).expect(404);
    await request(app).post(base+'/import').set('Authorization',otherAuth).send({code}).expect(404);
    expect(await SignCollection.countDocuments({userId:other})).toBe(1);
  });
  it('reviews mixed-topic collections, reuses progress and applies results only once',async()=>{
    const started=await request(app).post(base+'/'+id+'/quiz').set('Authorization',auth).send({}).expect(200),quiz=started.body.data;
    expect(quiz.collectionId).toBe(id);expect(quiz).not.toHaveProperty('topicId');expect(quiz.questions).toHaveLength(10);
    expect(JSON.stringify(quiz)).not.toContain('Nghĩa đã duyệt');
    const resumed=await request(app).post(base+'/'+id+'/quiz').set('Authorization',auth).send({}).expect(200);expect(resumed.body.data._id).toBe(quiz._id);
    const second=await request(app).post(base).set('Authorization',auth).send({name:'Bộ thứ hai'}).expect(201);
    await request(app).post(base+'/'+second.body.data._id+'/entries').set('Authorization',auth).send({entryIds:[String(entries[0])]}).expect(200);
    await request(app).post(base+'/'+second.body.data._id+'/quiz').set('Authorization',auth).send({}).expect(200);
    const record=await ReviewQuiz.findById(quiz._id);
    for(const q of record!.questions)await request(app).post('/api/v1/learning/quizzes/'+quiz._id+'/check').set('Authorization',auth).send({entryId:q.entryId,answer:q.word}).expect(200);
    const finished=await request(app).post('/api/v1/learning/quizzes/'+quiz._id+'/submit').set('Authorization',auth).send({}).expect(200);
    expect(finished.body.data.result.summary.independent).toBe(10);
    expect(await WordProgress.countDocuments({userId:owner})).toBe(10);
    expect(await TopicEnrollment.countDocuments({userId:owner})).toBe(2);
    expect(await LearningEvent.countDocuments({userId:owner,kind:'SELF_RATED',firstLearning:true})).toBe(9);
    await request(app).post('/api/v1/learning/quizzes/'+quiz._id+'/submit').set('Authorization',auth).send({}).expect(200);
    expect(await LearningEvent.countDocuments({userId:owner,quizId:quiz._id,kind:'QUIZ_REVIEWED'})).toBe(10);
    const secondDetail=await request(app).get(base+'/'+second.body.data._id).set('Authorization',auth).expect(200);
    expect(secondDetail.body.data.summary.remembered).toBe(1);
  });
  it('does not overwrite newer progress, removed words or hidden dictionary content',async()=>{
    const quiz=(await request(app).post(base+'/'+id+'/quiz').set('Authorization',auth).send({}).expect(200)).body.data;
    const stored=await ReviewQuiz.findById(quiz._id),first=stored!.questions[0],second=stored!.questions[1];
    await WordProgress.updateOne({userId:owner,entryId:first.entryId},{$set:{topicId:first.topicId,stage:'LEARNING',reviewedAt:new Date(Date.now()+60000)}},{upsert:true});
    await request(app).delete(base+'/'+id+'/entries/'+second.entryId).set('Authorization',auth).expect(200);
    for(const q of stored!.questions)await request(app).post('/api/v1/learning/quizzes/'+quiz._id+'/check').set('Authorization',auth).send({entryId:q.entryId,answer:q.word}).expect(200);
    const result=(await request(app).post('/api/v1/learning/quizzes/'+quiz._id+'/submit').set('Authorization',auth).send({}).expect(200)).body.data.result;
    expect(result.items.find((row:any)=>row.entryId===first.entryId).applied).toBe(false);
    expect(result.items.find((row:any)=>row.entryId===second.entryId).applied).toBe(false);
    await DictionaryEntry.updateOne({_id:entries[11]},{$set:{status:'ARCHIVED'}});
    const detail=await request(app).get(base+'/'+id+'?search=11').set('Authorization',auth).expect(200);expect(detail.body.data.items).toHaveLength(0);
  });
  it('discovers only explicitly published collections and removes listings without exposing private state',async()=>{
    await request(app).post(base+'/'+id+'/discovery').set('Authorization',auth).send({enabled:true}).expect(403);
    await User.updateOne({_id:owner},{$set:{isGuest:false}});
    const before=await request(app).get('/api/v1/shared-collections').expect(200);
    expect(before.body.data.items).toEqual([]);
    const empty=(await request(app).post(base).set('Authorization',auth).send({name:'Bộ rỗng'}).expect(201)).body.data;
    await request(app).post(base+'/'+empty._id+'/discovery').set('Authorization',auth).send({enabled:true}).expect(409);
    await request(app).post(base+'/'+id+'/discovery').set('Authorization',otherAuth).send({enabled:true}).expect(403);
    await request(app).post(base+'/'+id+'/discovery').set('Authorization',auth).send({enabled:true,owner:String(other)}).expect(400);
    const published=(await request(app).post(base+'/'+id+'/discovery').set('Authorization',auth).send({enabled:true}).expect(200)).body.data;
    expect(published.discoverable).toBe(true);expect(published.shareCode).toMatch(/^[a-f0-9]{32}$/);
    const again=(await request(app).post(base+'/'+id+'/discovery').set('Authorization',auth).send({enabled:true}).expect(200)).body.data;
    expect(again.shareCode).toBe(published.shareCode);
    const listing=(await request(app).get('/api/v1/shared-collections').expect(200)).body.data;
    expect(listing.items).toHaveLength(1);expect(listing.items[0]._id).toBe(id);expect(listing.items[0].wordCount).toBeGreaterThan(0);
    for(const field of ['userId','email','personalNote','progress','shareToken'])expect(JSON.stringify(listing)).not.toContain('"'+field+'"');
    await request(app).get('/api/v1/shared-collections?search=khongcobo').expect(200).then(result=>expect(result.body.data.pagination.total).toBe(0));
    await User.updateOne({_id:owner},{$set:{status:'SUSPENDED'}});
    await request(app).get('/api/v1/shared-collections').expect(200).then(result=>expect(result.body.data.items).toEqual([]));
    await User.updateOne({_id:owner},{$set:{status:'ACTIVE'}});
    await request(app).post(base+'/'+id+'/discovery').set('Authorization',auth).send({enabled:false}).expect(200);
    await request(app).get('/api/v1/shared-collections').expect(200).then(result=>expect(result.body.data.items).toEqual([]));
    await request(app).get('/api/v1/shared-collections/'+published.shareCode).expect(200);
    await request(app).post(base+'/'+id+'/discovery').set('Authorization',auth).send({enabled:true}).expect(200);
    await request(app).post(base+'/'+id+'/share').set('Authorization',auth).send({enabled:false}).expect(200);
    await request(app).get('/api/v1/shared-collections').expect(200).then(result=>expect(result.body.data.items).toEqual([]));
    await request(app).get('/api/v1/shared-collections/'+published.shareCode).expect(404);
    const imported=await SignCollection.findOne({userId:other}).lean();expect(imported?.discoverable).toBe(false);
    const explain=await SignCollection.find({discoverable:true}).sort({publishedAt:-1,_id:1}).explain('executionStats');
    expect(JSON.stringify(explain)).toContain('IXSCAN');
  });
  it('limits collection size and account count, removes owned data without deleting dictionary words',async()=>{
    const exported=await request(app).get('/api/v1/users/data/export').set('Authorization',auth).expect(200);
    expect(exported.body.data.signCollections.some((row:any)=>row._id===id)).toBe(true);
    expect(exported.body.data.signNotes.some((row:any)=>row.entryId===String(entries[0]))).toBe(true);
    expect(JSON.stringify(exported.body.data.signCollections)).not.toContain('shareToken');
    await SignCollection.updateOne({_id:id},{$set:{entryIds:Array.from({length:200},()=>new Types.ObjectId())}});
    await request(app).post(base+'/'+id+'/entries').set('Authorization',auth).send({entryIds:[String(entries[0])]}).expect(409);
    const current=await SignCollection.countDocuments({userId:other});
    await SignCollection.insertMany(Array.from({length:100-current},(_,i)=>({userId:other,name:'Giới hạn '+i})));
    await request(app).post(base).set('Authorization',otherAuth).send({name:'Quá giới hạn'}).expect(409);
    await userTransaction(owner,session=>clearOwnedData(owner,session));
    expect(await SignCollection.countDocuments({userId:owner})).toBe(0);expect(await SignNote.countDocuments({userId:owner})).toBe(0);
    expect(await DictionaryEntry.countDocuments({_id:{$in:entries}})).toBe(14);
  });
});
